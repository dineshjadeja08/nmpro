from typing import Protocol


class PaymentProvider(Protocol):
    def create_order(self, amount_paise: int, receipt: str) -> dict: ...
    def fetch_order(self, order_id: str) -> dict: ...
    def fetch_payment(self, payment_id: str) -> dict: ...
    def verify_checkout(self, order_id: str, payment_id: str, signature: str) -> bool: ...
    def verify_webhook(self, raw_body: bytes, signature: str) -> bool: ...
    def create_refund(self, payment_id: str, amount_paise: int, receipt: str) -> dict: ...
    def fetch_refund(self, refund_id: str) -> dict: ...
